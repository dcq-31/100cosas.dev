/**
 * Generates src/data/seo-redirects.mjs from tip content + git history.
 * Run: node scripts/generate-seo-redirects.mjs
 *
 * With trailingSlash: 'always', only one form per path is defined (trailing slash).
 */
import { readdirSync, writeFileSync } from "node:fs"
import { execSync } from "node:child_process"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

function loadTips(lang) {
  const map = new Map()
  const dir = join(root, "src/content/tips", lang)
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".md"))) {
    const slug = f.replace(/\.md$/, "")
    const num = String(parseInt(slug.match(/^(\d+)/)?.[1] || "", 10))
    if (num !== "NaN") map.set(num, slug)
  }
  return map
}

const es = loadTips("es")
const en = loadTips("en")
const authors = readdirSync(join(root, "src/content/authors"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))

const gitFiles = execSync(
  `git log --all --pretty=format: --name-only -- 'src/content/tips/**/*.md'`,
  { encoding: "utf8", cwd: root },
)
  .split("\n")
  .filter(Boolean)

const oldEs = new Set()
const oldEn = new Set()
for (const p of gitFiles) {
  const base = p.split("/").pop()?.replace(/\.md$/, "")
  if (!base || !/^\d+/.test(base)) continue
  if (base.includes('"') || base.includes("\\") || base.includes(" ")) continue
  if (p.includes("/en/")) oldEn.add(base)
  if (p.includes("/es/") || /^src\/content\/tips\/[^/]+\.md$/.test(p)) {
    oldEs.add(base)
  }
}

/** @type {Record<string, string>} */
const redirects = {
  // trailingSlash: 'always' — define only the slash form for page paths
  "/es/": "/",
  "/es/sobre-el-proyecto/": "/sobre-el-proyecto/",
  "/es/search-index.json": "/search-index.json",
  "/en/sobre-el-proyecto/": "/en/about-the-project/",
}

/** @param {string} from @param {string} to */
function add(from, to) {
  const fromNorm = from.includes(".")
    ? from
    : from.endsWith("/")
      ? from
      : `${from}/`
  const toNorm = to.includes(".") ? to : to.endsWith("/") ? to : `${to}/`
  redirects[fromNorm] = toNorm
}

for (const slug of es.values()) {
  add(`/es/consejo/${slug}`, `/consejo/${slug}/`)
}
for (const id of authors) {
  add(`/es/autor/${id}`, `/autor/${id}/`)
}

for (const [num, esSlug] of es) {
  const enSlug = en.get(num)
  if (!enSlug) continue
  add(`/en/consejo/${esSlug}`, `/en/tip/${enSlug}/`)
  add(`/tip/${enSlug}`, `/en/tip/${enSlug}/`)
}

for (const slug of oldEs) {
  if ([...es.values()].includes(slug)) continue
  const num = String(parseInt(slug.match(/^(\d+)/)?.[1] || "", 10))
  const current = es.get(num)
  if (!current) continue
  add(`/consejo/${slug}`, `/consejo/${current}/`)
  add(`/es/consejo/${slug}`, `/consejo/${current}/`)
}

for (const slug of oldEn) {
  if ([...en.values()].includes(slug)) continue
  const num = String(parseInt(slug.match(/^(\d+)/)?.[1] || "", 10))
  const current = en.get(num)
  if (!current) continue
  add(`/en/tip/${slug}`, `/en/tip/${current}/`)
  add(`/en/consejo/${slug}`, `/en/tip/${current}/`)
  add(`/tip/${slug}`, `/en/tip/${current}/`)
}

const extraOldEn = [
  "03-optimize-when-it-hurts",
  "03-the-most-damaging-phrase-in-the-language",
  "05-clean-code-is-not-the-goal",
  "07-the-most-damaging-phrase-in-the-language",
  "08-the-best-javascript-is-no-javascript",
  "12-dont-be-a-good-boy-scout-be-a-good-professional",
  "28-the-best-code-is-no-code-at-all",
]
for (const slug of extraOldEn) {
  if ([...en.values()].includes(slug)) continue
  const num = String(parseInt(slug.match(/^(\d+)/)?.[1] || "", 10))
  const current = en.get(num)
  if (!current) continue
  add(`/en/tip/${slug}`, `/en/tip/${current}/`)
  add(`/en/consejo/${slug}`, `/en/tip/${current}/`)
}

const out = join(root, "src/data/seo-redirects.mjs")
writeFileSync(
  out,
  `/** Auto-generated by scripts/generate-seo-redirects.mjs — do not edit by hand */\nexport const seoRedirects = ${JSON.stringify(redirects, null, 2)}\n`,
)
console.log(`Wrote ${Object.keys(redirects).length} redirects → ${out}`)
